
/*Ejercicio 4: Operadores de Asignación
Declare una variable con un valor inicial. Utilice operadores de asignación compuesta (+=,
-=, *=) para modificar su valor y muestre cada cambio en consola.*/

let valorInicial = 10;
let valor = valorInicial;

console.log("Ejercicio 4: Operadores de Asignación");
console.log("Valor inicial:", valor);

valor += 5;
console.log("\nDespués de += 5:", valor);

valor -= 3;
console.log("Después de -= 3:", valor);

valor *= 2;
console.log("Después de *= 2:", valor);

valor /= 4;
console.log("Después de /= 4:", valor);

valor %= 3;
console.log("Después de %= 3:", valor);



