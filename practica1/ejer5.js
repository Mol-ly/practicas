
/*Ejercicio 5: Promedio de Calificaciones
Declare tres variables con calificaciones numéricas. Calcule el promedio y muestre el
resultado.*/

let calificacion1 = 8.5;
let calificacion2 = 9.0;
let calificacion3 = 7.8;

let promedio = (calificacion1 + calificacion2 + calificacion3) / 3;

console.log("Ejercicio 5: Promedio de Calificaciones");
console.log("Calificación 1:", calificacion1);
console.log("Calificación 2:", calificacion2);
console.log("Calificación 3:", calificacion3);
console.log("\nPromedio de calificaciones:", promedio.toFixed(2));  